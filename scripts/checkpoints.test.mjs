import { test, after } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { pathToFileURL } from 'node:url'
import { bundle } from './lib/bundle.mjs'
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'gurt-checkpoints-test-'))
process.env.GURT_ROOT = path.join(root, 'state')
const outfile = path.join(root, 'bundle.mjs')
await bundle({ entryPoints: ['src/main/checkpoints.ts'], outfile })
const { Checkpoints, checkpointRef } = await import(pathToFileURL(outfile).href)
after(() => fs.rmSync(root, { recursive: true, force: true }))
const env = { ...process.env, GIT_AUTHOR_NAME: 'test', GIT_AUTHOR_EMAIL: 'test@local', GIT_COMMITTER_NAME: 'test', GIT_COMMITTER_EMAIL: 'test@local' }
function fixture(name) {
  const dir = path.join(root, name)
  fs.mkdirSync(dir)
  const git = (...args) => execFileSync('git', ['-C', dir, ...args], { env, encoding: 'utf8' }).trim()
  git('init', '-q')
  const write = (file, text) => fs.writeFileSync(path.join(dir, file), text)
  return { dir, git, write, cp: new Checkpoints(dir, { env, gitArgs: [] }) }
}
for (const unborn of [false, true]) test(`snapshot and restore preserve real index and HEAD (unborn=${unborn})`, async () => {
  const { dir, git, write, cp } = fixture(String(unborn))
  write('.gitignore', 'ignored/\n')
  write('tracked', 'original')
  git('add', '.')
  if (!unborn) git('commit', '-qm', 'initial')
  write('tracked', 'staged')
  write('new', 'new staged')
  git('add', '.')
  write('tracked', 'unstaged')
  write('untracked', 'untracked')
  fs.mkdirSync(path.join(dir, 'ignored'))
  write('ignored/data', 'keep')
  const index = fs.readFileSync(path.join(dir, '.git/index'))
  const head = fs.readFileSync(path.join(dir, '.git/HEAD'))
  const ref = checkpointRef('session', 1)
  const target = await cp.snapshot(ref)
  assert.equal(await cp.resolve(ref), target)
  assert.equal(git('show', `${target}:tracked`), 'unstaged')
  assert.equal(git('show', `${target}:new`), 'new staged')
  assert.equal(git('show', `${target}:untracked`), 'untracked')
  assert.ok(!git('ls-tree', '-r', '--name-only', target).includes('ignored'))
  write('tracked', 'later'); write('extra', 'delete me')
  fs.unlinkSync(path.join(dir, 'untracked'))
  write('ignored/data', 'still keep')
  const safety = checkpointRef('session', 'pre-rewind-123')
  const backup = await cp.snapshot(safety)
  await cp.restore(target, backup)
  assert.equal(fs.readFileSync(path.join(dir, 'tracked'), 'utf8'), 'unstaged')
  assert.equal(fs.readFileSync(path.join(dir, 'untracked'), 'utf8'), 'untracked')
  assert.ok(!fs.existsSync(path.join(dir, 'extra')))
  assert.equal(fs.readFileSync(path.join(dir, 'ignored/data'), 'utf8'), 'still keep')
  assert.deepEqual(fs.readFileSync(path.join(dir, '.git/index')), index)
  assert.deepEqual(fs.readFileSync(path.join(dir, '.git/HEAD')), head)
  assert.equal(git('show', `${backup}:extra`), 'delete me')
  await cp.prune('session', 1)
  await assert.rejects(cp.resolve(ref), /No checkpoint/)
  assert.equal(await cp.resolve(safety), backup)
  await cp.prune('session')
  await assert.rejects(cp.resolve(safety), /No checkpoint/)
})
test('large ignored directory is excluded; measure a 5000-file snapshot', async (t) => {
  const { dir, write, cp } = fixture('large')
  write('.gitignore', 'ignored/\n')
  fs.mkdirSync(path.join(dir, 'ignored'))
  for (let i = 0; i < 5000; i++) { write(`file-${i}`, 'content'); write(`ignored/${i}`, 'ignored') }
  const start = performance.now()
  await cp.snapshot(checkpointRef('session', 1))
  t.diagnostic(`5000 included + 5000 ignored files: ${Math.round(performance.now() - start)} ms`)
})
test('restore refuses changed-after-backup files and ignored collisions', async () => {
  const { dir, write, cp } = fixture('collisions')
  write('file', 'target')
  const target = await cp.snapshot(checkpointRef('s', 1))
  fs.unlinkSync(path.join(dir, 'file'))
  write('.gitignore', 'file\n')
  write('file', 'ignored data')
  const backup = await cp.snapshot(checkpointRef('s', 'pre-rewind-1'))
  await assert.rejects(cp.restore(target, backup))
  assert.equal(fs.readFileSync(path.join(dir, 'file'), 'utf8'), 'ignored data')
  write('.gitignore', '')
  const current = await cp.snapshot(checkpointRef('s', 'pre-rewind-2'))
  write('file', 'concurrent edit')
  await assert.rejects(cp.restore(target, current))
  assert.equal(fs.readFileSync(path.join(dir, 'file'), 'utf8'), 'concurrent edit')
})
test('retention keeps ten safety refs and earlier prompt checkpoints', async () => {
  const { cp } = fixture('retention')
  await cp.snapshot(checkpointRef('s', 1))
  for (let i = 100; i < 112; i++) await cp.snapshot(checkpointRef('s', `pre-rewind-${i}`))
  await cp.prune('s', 2)
  await cp.resolve(checkpointRef('s', 1))
  await assert.rejects(cp.resolve(checkpointRef('s', 'pre-rewind-100')))
  await cp.resolve(checkpointRef('s', 'pre-rewind-102'))
})
